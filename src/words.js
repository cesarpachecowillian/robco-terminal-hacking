/**
 * Checks every list: word length, A–Z only, no duplicates.
 * @param {Record<number, string[]>} lists
 * @returns {string[]} console messages, in list/word order
 */
export function validateWordLists(lists) {
  const errors = [];
  Object.entries(lists).forEach(([len, words]) => {
    const seen = new Set();
    words.forEach(w => {
      if (w.length !== +len)
        errors.push(`[WORDLIST] "${w}" in [${len}] has length ${w.length}`);
      if (!/^[A-Z]+$/.test(w))
        errors.push(`[WORDLIST] "${w}" in [${len}] has invalid chars`);
      if (seen.has(w))
        errors.push(`[WORDLIST] duplicate "${w}" in [${len}]`);
      seen.add(w);
    });
  });
  return errors;
}

